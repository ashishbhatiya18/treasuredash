-- PostgreSQL schema, generated from schema.sql (keep them in step).
-- Tables are ordered so every foreign key points at an existing table.
-- All money columns are integer paise; dates and timestamps are ISO text.
-- Text uses the byte-wise "C" collation so sorting matches SQLite exactly.

-- All money columns are integer paise.

CREATE TABLE IF NOT EXISTS settings (
  key   TEXT COLLATE "C" PRIMARY KEY,
  value TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS flats (
  code      TEXT COLLATE "C" PRIMARY KEY,
  owner     TEXT COLLATE "C" NOT NULL,
  area_sqft DOUBLE PRECISION NOT NULL,
  phone1    TEXT COLLATE "C" NOT NULL DEFAULT '',
  phone2    TEXT COLLATE "C" NOT NULL DEFAULT '',
  email1    TEXT COLLATE "C" NOT NULL DEFAULT '',
  email2    TEXT COLLATE "C" NOT NULL DEFAULT '',
  notes     TEXT COLLATE "C" NOT NULL DEFAULT '',
  sort_key  BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS periods (
  id            TEXT COLLATE "C" PRIMARY KEY,           -- Q3FY26
  fy            BIGINT NOT NULL,
  quarter       BIGINT NOT NULL,
  start_date    TEXT COLLATE "C" NOT NULL,
  end_date      TEXT COLLATE "C" NOT NULL,
  due_date      TEXT COLLATE "C" NOT NULL,
  rate_per_sqft DOUBLE PRECISION NOT NULL,              -- per month
  late_fee      BIGINT NOT NULL,           -- per month of delay
  auto_late_fee BIGINT NOT NULL DEFAULT 1, -- 0 for periods imported from the sheet
  status        TEXT COLLATE "C" NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed')),
  invoiced_at   TEXT COLLATE "C"
);

CREATE TABLE IF NOT EXISTS bank_statements (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filename    TEXT COLLATE "C" NOT NULL,
  sha256      TEXT COLLATE "C" NOT NULL UNIQUE,
  account_no  TEXT COLLATE "C" NOT NULL DEFAULT '',
  from_date   TEXT COLLATE "C",
  to_date     TEXT COLLATE "C",
  opening     BIGINT,
  closing     BIGINT,
  uploaded_at TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS bank_txns (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  statement_id BIGINT NOT NULL REFERENCES bank_statements(id),
  date         TEXT COLLATE "C" NOT NULL,
  value_date   TEXT COLLATE "C" NOT NULL DEFAULT '',
  narration    TEXT COLLATE "C" NOT NULL,
  ref_no       TEXT COLLATE "C" NOT NULL,
  debit        BIGINT NOT NULL DEFAULT 0,
  credit       BIGINT NOT NULL DEFAULT 0,
  balance      BIGINT NOT NULL,
  payer_key    TEXT COLLATE "C" NOT NULL DEFAULT '',
  payer_name   TEXT COLLATE "C" NOT NULL DEFAULT '',
  -- review workflow
  status       TEXT COLLATE "C" NOT NULL DEFAULT 'review' CHECK (status IN ('review','matched','ignored','historical')),
  kind         TEXT COLLATE "C" NOT NULL DEFAULT '' CHECK (kind IN ('','maintenance','other_income','expense','transfer')),
  flat         TEXT COLLATE "C" REFERENCES flats(code),
  payee        TEXT COLLATE "C" NOT NULL DEFAULT '',
  category     TEXT COLLATE "C" NOT NULL DEFAULT '',
  confidence   BIGINT NOT NULL DEFAULT 0,
  reasons      TEXT COLLATE "C" NOT NULL DEFAULT '[]',  -- JSON array of strings
  UNIQUE (date, ref_no, debit, credit, balance)
);

-- Per-flat running account. Positive = owner owes, negative = owner paid/credited.
CREATE TABLE IF NOT EXISTS ledger (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flat        TEXT COLLATE "C" NOT NULL REFERENCES flats(code),
  date        TEXT COLLATE "C" NOT NULL,
  kind        TEXT COLLATE "C" NOT NULL CHECK (kind IN ('opening','invoice','late_fee','payment','adjustment')),
  period_id   TEXT COLLATE "C" REFERENCES periods(id),
  seq         BIGINT,                      -- late fee month number; 0 for invoices
  amount      BIGINT NOT NULL,
  description TEXT COLLATE "C" NOT NULL DEFAULT '',
  mode        TEXT COLLATE "C" NOT NULL DEFAULT '',     -- bank / gpay_personal / cash / via_caretaker
  bank_txn_id BIGINT REFERENCES bank_txns(id) ON DELETE CASCADE,
  source      TEXT COLLATE "C" NOT NULL DEFAULT 'app',  -- app / import
  created_at  TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (flat, period_id, kind, seq)
);

CREATE INDEX IF NOT EXISTS ledger_flat_date ON ledger(flat, date);

-- Learned identities of payers (UPI handle, source account, name) → flat or payee.
CREATE TABLE IF NOT EXISTS payer_aliases (
  key        TEXT COLLATE "C" PRIMARY KEY,
  flat       TEXT COLLATE "C" REFERENCES flats(code),
  payee      TEXT COLLATE "C" NOT NULL DEFAULT '',
  category   TEXT COLLATE "C" NOT NULL DEFAULT '',
  created_at TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS categories (
  name     TEXT COLLATE "C" PRIMARY KEY,
  in_pnl   BIGINT NOT NULL DEFAULT 1,
  keywords TEXT COLLATE "C" NOT NULL DEFAULT '',        -- comma separated, matched against description
  priority BIGINT NOT NULL DEFAULT 100     -- lower wins
);

CREATE TABLE IF NOT EXISTS expenses (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date        TEXT COLLATE "C" NOT NULL,
  description TEXT COLLATE "C" NOT NULL,
  category    TEXT COLLATE "C" NOT NULL REFERENCES categories(name) ON UPDATE CASCADE,
  payee       TEXT COLLATE "C" NOT NULL DEFAULT '',
  amount      BIGINT NOT NULL,
  bank_txn_id BIGINT REFERENCES bank_txns(id) ON DELETE SET NULL,
  bill_file   TEXT COLLATE "C" NOT NULL DEFAULT '',
  notes       TEXT COLLATE "C" NOT NULL DEFAULT '',
  source      TEXT COLLATE "C" NOT NULL DEFAULT 'app',
  created_at  TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX IF NOT EXISTS expenses_date ON expenses(date);

CREATE TABLE IF NOT EXISTS other_income (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date        TEXT COLLATE "C" NOT NULL,
  category    TEXT COLLATE "C" NOT NULL,                -- Bank interest / Move-in charges / Other
  description TEXT COLLATE "C" NOT NULL DEFAULT '',
  amount      BIGINT NOT NULL,
  flat        TEXT COLLATE "C" REFERENCES flats(code),
  bank_txn_id BIGINT REFERENCES bank_txns(id) ON DELETE CASCADE,
  created_at  TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS reminders (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_id  TEXT COLLATE "C" NOT NULL REFERENCES periods(id),
  seq        BIGINT NOT NULL,
  text       TEXT COLLATE "C" NOT NULL,
  flats      TEXT COLLATE "C" NOT NULL,                 -- JSON array
  status     TEXT COLLATE "C" NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','sent')),
  created_at TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  sent_at    TEXT COLLATE "C"
);

-- Fixed / recurring deposits: association money held outside the savings account.
CREATE TABLE IF NOT EXISTS deposits (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind            TEXT COLLATE "C" NOT NULL CHECK (kind IN ('FD','RD')),
  bank            TEXT COLLATE "C" NOT NULL DEFAULT '',
  number          TEXT COLLATE "C" NOT NULL DEFAULT '',
  opened_on       TEXT COLLATE "C" NOT NULL,
  principal       BIGINT NOT NULL DEFAULT 0, -- FD amount
  installment     BIGINT NOT NULL DEFAULT 0, -- RD monthly instalment
  tenure_months   BIGINT NOT NULL DEFAULT 12,
  rate            DOUBLE PRECISION NOT NULL DEFAULT 0,    -- % p.a.
  maturity_date   TEXT COLLATE "C" NOT NULL DEFAULT '',
  maturity_amount BIGINT NOT NULL DEFAULT 0,
  closed_on       TEXT COLLATE "C",                       -- matured / broken
  notes           TEXT COLLATE "C" NOT NULL DEFAULT ''
);

-- Money moved between the savings account and a deposit, as booked by the
-- treasurer. Until the matching bank line is imported it adjusts the savings
-- balance; once matched (bank_txn_id) the statement already reflects it.
CREATE TABLE IF NOT EXISTS deposit_fundings (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deposit_id  BIGINT NOT NULL REFERENCES deposits(id) ON DELETE CASCADE,
  date        TEXT COLLATE "C" NOT NULL,
  kind        TEXT COLLATE "C" NOT NULL CHECK (kind IN ('open','installment','close')),
  amount      BIGINT NOT NULL,             -- + savings → deposit, − deposit → savings
  bank_txn_id BIGINT REFERENCES bank_txns(id) ON DELETE SET NULL,
  income_id   BIGINT REFERENCES other_income(id) ON DELETE SET NULL
);

-- Entries removed as corrections (e.g. a payment the sheet recorded but that was
-- never received). The original row is kept so the change can be undone.
CREATE TABLE IF NOT EXISTS ledger_voids (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ledger_id   BIGINT NOT NULL,
  flat        TEXT COLLATE "C" NOT NULL,
  date        TEXT COLLATE "C" NOT NULL,
  kind        TEXT COLLATE "C" NOT NULL,
  period_id   TEXT COLLATE "C",
  seq         BIGINT,
  amount      BIGINT NOT NULL,
  description TEXT COLLATE "C" NOT NULL,
  mode        TEXT COLLATE "C" NOT NULL,
  source      TEXT COLLATE "C" NOT NULL,
  reason      TEXT COLLATE "C" NOT NULL,
  voided_at   TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  restored_at TEXT COLLATE "C"
);

-- Beneficiary details for vendors / staff the association pays.
CREATE TABLE IF NOT EXISTS payees (
  name         TEXT COLLATE "C" PRIMARY KEY,           -- as used in expenses.payee
  method       TEXT COLLATE "C" NOT NULL DEFAULT 'NEFT', -- NEFT / IMPS / UPI / BillPay / Cheque / Cash
  account_name TEXT COLLATE "C" NOT NULL DEFAULT '',
  account_no   TEXT COLLATE "C" NOT NULL DEFAULT '',
  ifsc         TEXT COLLATE "C" NOT NULL DEFAULT '',
  upi          TEXT COLLATE "C" NOT NULL DEFAULT '',
  reference    TEXT COLLATE "C" NOT NULL DEFAULT '',  -- e.g. Bescom consumer / account ID
  notes        TEXT COLLATE "C" NOT NULL DEFAULT ''
);

